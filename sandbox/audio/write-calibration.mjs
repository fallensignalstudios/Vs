#!/usr/bin/env node
/**
 * Writes src/audio/calibration.ts from the sandbox calibration pass:
 *   node tools/shot.cjs "/sandbox/audio/?calibrate=1" --timeout 900000 --eval "__calibration" | node sandbox/audio/write-calibration.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const input = fs.readFileSync(0, 'utf8');
const line = input.split('\n').find((l) => l.startsWith('[eval] {') && l.includes('"sfx"'));
if (!line) {
  console.error('no calibration JSON found on stdin');
  process.exit(1);
}
const cal = JSON.parse(line.slice('[eval] '.length));
const table = (o) =>
  Object.keys(o).sort().map((k) => `  ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${Number(o[k].toPrecision(4))},`).join('\n');
const out = `/**
 * Measured normalisation (GENERATED by the audio sandbox — do not edit by hand):
 *   node tools/shot.cjs "/sandbox/audio/?calibrate=1" --timeout 900000 --eval "__calibration" | node sandbox/audio/write-calibration.mjs
 * SFX_NORM[id] scales a recipe so its peak at the final output (through the whole mix chain, reference volume
 * settings) lands on the recipe's authored \`db\`. MUSIC_NORM / AMB_NORM do the same for the RMS of each bed.
 * Missing entries fall back to defaults and the sandbox report flags them NOCAL.
 */
export const SFX_NORM: Readonly<Record<string, number>> = {
${table(cal.sfx)}
};

export const MUSIC_NORM: Readonly<Record<string, number>> = {
${table(cal.music)}
};

export const AMB_NORM: Readonly<Record<string, number>> = {
${table(cal.amb)}
};
`;
const file = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../src/audio/calibration.ts');
fs.writeFileSync(file, out);
console.log(`wrote ${file}: ${Object.keys(cal.sfx).length} sfx, ${Object.keys(cal.music).length} music, ${Object.keys(cal.amb).length} ambience`);
if (cal.log) console.log(cal.log.join('\n'));
